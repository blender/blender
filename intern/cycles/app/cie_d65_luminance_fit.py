# Wavelengths in um
x = [x * 0.001 for x in range(380, 781)]


def sigmoid(x, a, x0):
    return 1 / (1 + np.exp(-a * (x - x0)))


def normalized_sigmoid(x, a, x0):
    y = sigmoid(x, a, x0)
    # Normalization factor so that the function evaluates to 0 at 380nm and 1 at 780nm
    y0 = sigmoid(0.38, a, x0)
    N = sigmoid(0.78, a, x0) - y0
    return (y - y0) / N


# Compute luminance
sum = 0.0
luminance = list(range(380, 781))
for i in range(0, 401):
    # Sampling purely based on luminance would give high weights to green wavelengths,
    # which leads to color noise. We want a bit of all the wavelengths, so add some constant.
    # The choice of 0.25 is kind of random
    luminance[i] = (cie_y[i] + 0.25) * cie_d65_spd[i]
    sum += luminance[i]


# Compute cdf
partial_sum = 0.0
luminance_cdf = list(range(380, 781))
for i in range(0, 401):
    partial_sum += luminance[i]
    luminance_cdf[i] = partial_sum / sum


# Initial guess
p0 = [40, 0.58]

# Fit cdf to a sigmoid
popt, pcov = curve_fit(normalized_sigmoid, x, luminance_cdf, p0, method='lm')

# Print fitted result
a = popt[0]
x0 = popt[1]
y0 = sigmoid(0.38, a, x0)
N = sigmoid(0.78, a, x0) - y0
print(a, x0, y0, N)


# Plot original function and fitted function
plt.figure(figsize=(10, 6))
label_tex = rf"$F(x) = \frac{{\frac{{1}}{{1 + e^{{-{a:.5f}(x - {x0:.5f})}}}} - {y0:.5f}}}{{{N:.5f}}}$"
plt.plot(x, normalized_sigmoid(x, *popt), label=label_tex, linestyle='--')
plt.plot(x, luminance_cdf, label='Luminance cdf')


# Labels and legend
plt.xlabel('Wavelength/um')
plt.title('Fit luminance cdf to a normalized sigmoid')
plt.legend(fontsize=20)
plt.grid(True)

plt.tight_layout()
plt.show()
